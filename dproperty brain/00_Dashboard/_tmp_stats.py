import statistics as st

def stats(name, prices, areas):
    print(f"--- {name} ---")
    print(f"n={len(prices)}")
    print(f"price min={min(prices)} max={max(prices)} median={st.median(prices):.0f} mean={st.mean(prices):.0f}")
    print(f"area  min={min(areas)} max={max(areas)} median={st.median(areas):.2f} mean={st.mean(areas):.2f}")

